#!/usr/bin/env node
// Regenerate `decisions/INDEX.md` from the per-decision files.
//
// The decision log used to be one 212 KB `DECISIONS.md`. That made it the only
// hand-edited file in the repo large enough to exceed a tool's read budget, and
// in #59 something read it truncated and wrote the truncation back: the file was
// an unreadable blob for three commits, with 689 lines of entries silently gone
// (issue #70). Splitting it removes the hazard rather than guarding it — no
// single file is near any budget now, and an edit touches one small file.
//
// The index is a build output, so it needs the same treatment every other build
// output in this repo gets: generated from the source of truth, and checked in
// CI so it cannot quietly stop describing it.
//
//   node scripts/build-decisions-index.mjs           # write decisions/INDEX.md
//   node scripts/build-decisions-index.mjs --check   # fail if it is stale

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'decisions';
const INDEX = join(DIR, 'INDEX.md');
const check = process.argv.includes('--check');

const PREAMBLE = `# Decision Log

Architectural decisions for ai2rules (the umbrella project; flagship layer = the
governance harness), with the alternatives we weighed and why we chose what we did.
ADR-lite: one entry per decision, one file per entry.

**Why this exists:** so a choice can be revisited later without re-deriving the
context — especially the alternatives we *didn't* take.

**How to add one:** create \`decisions/D<nnn>-<slug>.md\` with a \`# D<n> — Title\`
heading when you make a decision that closes off a real alternative, then run
\`node scripts/build-decisions-index.mjs\` to refresh this index. Keep entries
short; link to the epic in \`PLAN.md\`, the commit, or the code. Status is
\`Accepted\` unless later \`Superseded by D<n>\`.

**Do not edit this file by hand** — it is generated, and CI checks it.

> Entries D1–D11 were reconstructed from project artifacts (commits, \`PLAN.md\`,
> the plan files, code comments, \`CLAUDE.md\`) rather than a contemporaneous log,
> so dates are approximate. D12 onward are recorded as decisions are made.

| Field | Meaning |
|---|---|
| **Decision** | what we chose |
| **Alternatives** | the options we rejected |
| **Why** | the deciding rationale |
`;

/** Read every decision file, newest number last. */
function entries() {
  const files = readdirSync(DIR)
    .filter((f) => /^D\d{3}-.+\.md$/.test(f))
    .sort();
  return files.map((file) => {
    const text = readFileSync(join(DIR, file), 'utf8');
    const heading = text.match(/^# D(\d+) — (.+)$/m);
    if (!heading) {
      fail(`${file}: no "# D<n> — Title" heading on the first line`);
    }
    const number = Number(heading[1]);
    const expected = `D${String(number).padStart(3, '0')}-`;
    if (!file.startsWith(expected)) {
      fail(`${file}: heading says D${number}, so the filename must start "${expected}"`);
    }
    return {
      number,
      title: heading[2].trim(),
      file,
      epic: (text.match(/\*\*Epic:\*\*\s*([^·\n*]+)/) ?? [])[1]?.trim() ?? '',
      status: (text.match(/\*\*Status:\*\*\s*([^·\n*]+)/) ?? [])[1]?.trim() ?? '',
    };
  });
}

function render(all) {
  const rows = all
    .map((e) => {
      // Pipes and newlines would break the table; titles are prose, so escape.
      const title = e.title.replaceAll('|', '\\|');
      return `| [D${e.number}](${e.file}) | ${title} | ${e.epic || '—'} | ${e.status || '—'} |`;
    })
    .join('\n');
  return `${PREAMBLE}
---

**${all.length} decisions.** Each links to its own file.

| # | Decision | Epic | Status |
|---|---|---|---|
${rows}
`;
}

function fail(message) {
  console.error(`build-decisions-index: ${message}`);
  process.exit(1);
}

const all = entries();

// The numbering is the log's identity: gaps and duplicates both mean somebody's
// entry is about to be overwritten or lost.
const numbers = all.map((e) => e.number);
const duplicates = numbers.filter((n, i) => numbers.indexOf(n) !== i);
if (duplicates.length) fail(`duplicate decision numbers: ${[...new Set(duplicates)].join(', ')}`);
for (let i = 0; i < numbers.length; i++) {
  if (numbers[i] !== i + 1) {
    fail(`decision numbers must run 1..${numbers.length} with no gaps; found D${numbers[i]} where D${i + 1} was expected`);
  }
}

const wanted = render(all);
if (check) {
  let current = '';
  try {
    current = readFileSync(INDEX, 'utf8');
  } catch {
    fail(`${INDEX} is missing. Run: node scripts/build-decisions-index.mjs`);
  }
  if (current !== wanted) {
    fail(`${INDEX} is stale (${all.length} decisions on disk). Run: node scripts/build-decisions-index.mjs`);
  }
  console.log(`decisions/INDEX.md is current — ${all.length} decisions.`);
} else {
  writeFileSync(INDEX, wanted);
  console.log(`wrote ${INDEX} — ${all.length} decisions.`);
}
