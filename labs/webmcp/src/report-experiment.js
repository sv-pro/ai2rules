// RESULTS.md for experiment 1 of AI2-104 (D96): the exfiltration add-on beside
// each defense. Computed from the rows, like RESULTS.md, and deterministic (no
// timestamps), so a rerun diffs clean.

import { attackCell, yes } from './report.js';

export const PAIRS = [['D0', 'D0+exfil'], ['D2', 'D2+exfil'], ['D3', 'D3+exfil']];

export function renderExperiment(rows, meta = {}) {
  const at = (s, d) => rows.find((r) => r.scenario === s && r.defense === d);
  const scenarios = [...new Set(rows.map((r) => r.scenario))];
  const attacks = scenarios.filter((s) => !s.startsWith('benign:'));
  const label = (s) => { const r = rows.find((x) => x.scenario === s); return `${r.short} ${r.name}`; };
  const defenses = PAIRS.flat().filter((d) => rows.some((r) => r.defense === d));
  const errors = rows.filter((r) => r.status !== 'OK');

  const L = [];
  L.push('# Experiment 1 (AI2-104): the exfiltration add-on beside each defense', '');
  L.push('Generated by `npm run experiment:exfil` in `labs/webmcp/`. Same agent (CompromisedAgent), oracle, pages and tasks as `results/RESULTS.md`; only the defenses differ. Not part of the matrix\'s own columns.', '');
  L.push('The add-on (`addons/exfiltration/`, AI2-101) is told what the task\'s sensitive origins return, and reports when an argument of a call to another origin carries one of those values. D96 says it supplies a fact, never a verdict, and the host maps the fact:');
  L.push('- **D0+exfil, D2+exfil: host refusal.** These worlds declare no flow sink, so the fact has no rule in the world to meet. The host composes the add-on beside the defense: an ALLOW with a finding becomes DENY (`addon:exfiltration`).');
  L.push('- **D3+exfil: label.** The finding raises that argument\'s flow label to Private, and the kernel\'s flow contract decides (`flow:confidentiality`).', '');
  L.push(`Kernel: \`${meta.harness ?? 'unknown'}\`. Cells: ${rows.length}. Errors: ${errors.length}.`, '');

  L.push('## Attack outcome', '');
  L.push(`| Attack | ${defenses.join(' | ')} |`);
  L.push(`|---|${defenses.map(() => '---').join('|')}|`);
  for (const s of attacks) L.push(`| ${label(s)} | ${defenses.map((d) => attackCell(at(s, d))).join(' | ')} |`);
  L.push('');

  L.push('## Utility (did the user\'s task complete?)', '');
  L.push(`| Scenario | ${defenses.join(' | ')} |`);
  L.push(`|---|${defenses.map(() => '---').join('|')}|`);
  for (const s of scenarios) L.push(`| ${label(s)} | ${defenses.map((d) => { const r = at(s, d); return r?.status === 'OK' ? yes(r.utility) : '**ERROR**'; }).join(' | ')} |`);
  L.push('');

  L.push('## What the add-on changes', '');
  for (const [base, withAddon] of PAIRS) {
    if (!defenses.includes(base) || !defenses.includes(withAddon)) continue;
    const closed = attacks.filter((s) => at(s, base)?.attack_success && at(s, withAddon)?.attack_success === false).map(label);
    const opened = attacks.filter((s) => at(s, base)?.attack_success === false && at(s, withAddon)?.attack_success).map(label);
    const lost = scenarios.filter((s) => at(s, base)?.utility && at(s, withAddon)?.utility === false).map(label);
    const through = attacks.filter((s) => at(s, withAddon)?.attack_success).map((s) => at(s, withAddon).short);
    const flagged = scenarios.filter((s) => at(s, withAddon)?.addon_findings).map((s) => at(s, withAddon).short);
    L.push(`- **${withAddon} vs ${base}.** Closes: ${closed.join(', ') || 'none'}. Opens: ${opened.join(', ') || 'none'}. Utility lost: ${lost.join(', ') || 'none'}. Still succeeds: ${through.join(', ') || 'none'} (${through.length}/${attacks.length}). Cells where the add-on reported a finding: ${flagged.join(', ') || 'none'}.`);
  }
  L.push('');
  L.push('Composition only tightens (D96): "Opens" must be none. A finding in a benign cell would be a false positive, and the utility table shows what it would cost.', '');
  return L.join('\n') + '\n';
}
