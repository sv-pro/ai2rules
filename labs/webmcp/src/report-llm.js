// RESULTS-LLM.md: the LLMAgent stretch column (docs/LLM-AGENT.md). A separate
// table from RESULTS.md, because a model that refuses an injection lowers the
// attack-success rate without any defense doing anything.
export const LLM_TASKS = ['shop-buy', 'crm-gift'];

const cellText = (r) => {
  if (!r) return '';
  if (r.status !== 'OK') return '**ERROR**';
  if (r.attack_success === null) return r.leak_or_effect_without_attack ? 'unexpected effect' : '—';
  return r.attack_success ? '**succeeded**' : `not achieved (${r.stopped_by})`;
};

const statsText = (r) => {
  const s = r?.agent_stats;
  return s ? `${s.turns}t/${s.tool_calls}c/${s.pages_read}p ${s.stop}` : '';
};

export function renderLlmResults(rows) {
  const scenarios = [...new Set(rows.map((r) => r.scenario))];
  const defenses = [...new Set(rows.map((r) => r.defense))];
  const models = [...new Set(rows.map((r) => r.agent_stats?.model).filter(Boolean))];
  const at = (s, d) => rows.find((r) => r.scenario === s && r.defense === d);
  const lines = [
    '# WebMCP attack lab — LLMAgent stretch column',
    '',
    `Generated by \`node src/run.js --agent llm\` (model: ${models.join(', ') || 'unknown'}). Same oracle, defenses and pages as RESULTS.md, but the agent is a real model that may ignore or refuse an injection. **"Not achieved" here is not a defense result**: the mechanism in brackets is \`none\` when the model itself declined. Results can differ between runs (docs/LLM-AGENT.md). \`ERROR\` means the lab or the API call failed.`,
    '',
    `| Scenario | Task | ${defenses.map((d) => `${d} attack`).join(' | ')} | ${defenses.map((d) => `${d} utility`).join(' | ')} | ${defenses.map((d) => `${d} agent`).join(' | ')} |`,
    `|---|---|${defenses.map(() => '---').join('|')}|${defenses.map(() => '---').join('|')}|${defenses.map(() => '---').join('|')}|`,
  ];
  for (const s of scenarios) {
    const first = rows.find((r) => r.scenario === s);
    lines.push(`| ${first.short} ${first.name} | ${first.task} | ${defenses.map((d) => cellText(at(s, d))).join(' | ')} | ${defenses.map((d) => {
      const r = at(s, d);
      return r?.status === 'OK' ? (r.utility ? 'yes' : '**no**') : '';
    }).join(' | ')} | ${defenses.map((d) => statsText(at(s, d))).join(' | ')} |`);
  }
  lines.push(
    '',
    'Agent column: model turns / page-tool calls / pages read, then the last stop reason (`max_steps` when the step budget ran out).',
    '',
    'Traces: `results/traces-llm/<scenario>--<defense>.jsonl`; every model turn is an `llm_turn` record.',
    '',
  );
  return lines.join('\n');
}
