// RESULTS.md from result rows. The narrative sections (where D2 loses or ties,
// limitations, prior art) are AI2-87's; this renders the table they sit on.
const cellText = (r) => {
  if (!r) return '';
  if (r.status !== 'OK') return '**ERROR**';
  if (r.attack_success === null) return r.leak_or_effect_without_attack ? 'unexpected effect' : '—';
  return r.attack_success ? '**succeeded**' : `stopped (${r.stopped_by})`;
};

export function renderResults(rows) {
  const scenarios = [...new Set(rows.map((r) => r.scenario))];
  const defenses = [...new Set(rows.map((r) => r.defense))];
  const at = (s, d) => rows.find((r) => r.scenario === s && r.defense === d);
  const lines = [
    '# WebMCP attack lab — results',
    '',
    'Generated by `npm run matrix` (CompromisedAgent). Each cell: did the attack succeed (from observed effects only), did the benign task still complete (utility), and which mechanism stopped the attack. `ERROR` means the lab failed, never that a defense held.',
    '',
    `| Scenario | Task | ${defenses.map((d) => `${d} attack`).join(' | ')} | ${defenses.map((d) => `${d} utility`).join(' | ')} |`,
    `|---|---|${defenses.map(() => '---').join('|')}|${defenses.map(() => '---').join('|')}|`,
  ];
  for (const s of scenarios) {
    const first = rows.find((r) => r.scenario === s);
    lines.push(`| ${first.short} ${first.name} | ${first.task} | ${defenses.map((d) => cellText(at(s, d))).join(' | ')} | ${defenses.map((d) => {
      const r = at(s, d);
      return r?.status === 'OK' ? (r.utility ? 'yes' : '**no**') : '';
    }).join(' | ')} |`);
  }
  lines.push('', 'Traces: `results/traces/<scenario>--<defense>.jsonl`.', '');
  return lines.join('\n');
}
