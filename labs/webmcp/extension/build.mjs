#!/usr/bin/env node
// Assembles the unpacked extension in extension/dist/ (DESIGN.md §8). Nothing
// the extension decides with is written here by hand; it is copied or derived
// from the one source each thing has:
//   - the kernel: the committed WASM engine, blog/public/vendor/harness-wasm/
//     (the artifact check-wasm-freshness.mjs holds to the Rust source);
//   - the agent: the lab's CompromisedAgent, src/agent/compromised.js, verbatim;
//   - the task, the worlds and the canary: the lab's tasks.js, worldYaml() and
//     canary.js, evaluated here and written out as data (lab-data.js);
//   - the origins: the demo page server's (serve.mjs).
//
//   node extension/build.mjs      # then load extension/dist/ unpacked
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TASKS } from '../src/tasks.js';
import { worldYaml } from '../src/defenses/d2-ai2rules.js';
import { CANARY } from '../src/canary.js';
import { SHOP_ACCOUNT } from '../src/servers.js';
import { DEMO_ORIGINS } from './serve.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const LAB_ROOT = path.resolve(HERE, '..');
const REPO_ROOT = path.resolve(LAB_ROOT, '..', '..');
export const DIST = path.join(HERE, 'dist');

export const SCENARIO_ID = 's5b-read-sink-exfil';

export async function labData() {
  const scenario = (await import(new URL(`../scenarios/${SCENARIO_ID}/scenario.js`, import.meta.url))).default;
  const task = TASKS[scenario.task];
  // Data only: the extension never runs the lab's oracle functions.
  const { utility: _utility, ...taskData } = task;
  return {
    SCENARIO: { id: SCENARIO_ID, short: scenario.short, name: scenario.name },
    TASK: taskData,
    WORLDS: { D2: worldYaml(task), D3: worldYaml(task, { labels: true }) },
    ORIGINS: DEMO_ORIGINS,
    CANARY,
    SHOP_ACCOUNT,
  };
}

export async function build() {
  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(path.join(DIST, 'vendor'), { recursive: true });
  cpSync(path.join(HERE, 'src'), DIST, { recursive: true });
  cpSync(path.join(LAB_ROOT, 'src', 'agent', 'compromised.js'), path.join(DIST, 'compromised.js'));
  for (const f of ['harness_wasm.js', 'harness_wasm_bg.wasm']) {
    cpSync(path.join(REPO_ROOT, 'blog', 'public', 'vendor', 'harness-wasm', f), path.join(DIST, 'vendor', f));
  }
  const data = await labData();
  const body = Object.entries(data).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)};`).join('\n\n');
  writeFileSync(path.join(DIST, 'lab-data.js'), `// Generated by extension/build.mjs from the lab's sources. Do not edit.\n${body}\n`);
  const manifest = JSON.parse(readFileSync(path.join(DIST, 'manifest.json'), 'utf8'));
  return { dist: DIST, version: manifest.version };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { dist } = await build();
  console.log(`built ${path.relative(process.cwd(), dist) || dist} — load it unpacked at chrome://extensions`);
}
